/**
 * Признак подменённого решения.
 *
 * Вынесено отдельным модулем ради проверок: `classify-courses.mjs` на верхнем
 * уровне читает каталог и пишет отчёты, импортировать его из тестов нельзя.
 *
 * Различать нужно два разных случая. `print("Москва")` и `city = "Казань"` —
 * нормальные задания для новичка: строка здесь данные, а проверяется код
 * вокруг неё. `artifact = "профиль дерева"` — подмена: человек не пишет код,
 * а вписывает формулировку под заранее известное имя.
 */

/**
 * Многословная русская строка.
 *
 * Отличает подмену не кириллица и не присваивание, а многословность:
 * подменённое решение — это всегда фраза, а не значение. Ловить присваивание
 * нельзя: под подозрение попадёт первая же миссия про переменные.
 */
export const CYRILLIC_PHRASE = /"[^"]*[а-яёА-ЯЁ][^"]*\s[^"]*"/

/**
 * Код вокруг фразы.
 *
 * Одной многословности мало: `print(f"Склад {code} принял {parcels}")` — тоже
 * фраза, но проверяется в ней подстановка значений, а формулировка приходит из
 * задания. Подмена решения выглядит иначе: `artifact = "профиль дерева"` — это
 * присваивание фразы и больше ничего. Отличает их наличие вызова или
 * конструкции языка вокруг литерала.
 */
export const CARRIES_STRUCTURE =
  /[()]|^\s*(?:def|class|for|while|if|elif|else|with|try|except|return|import|from|yield|raise)\b/m

export const isCyrillicLiteral = fragment =>
  CYRILLIC_PHRASE.test(fragment) && !CARRIES_STRUCTURE.test(fragment)
