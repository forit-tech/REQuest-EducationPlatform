function allocate(total, blocks) {
  const base = Math.floor(total / blocks)
  const remainder = total % blocks
  return Array.from({ length: blocks }, (_, index) => base + (index < remainder ? 1 : 0))
}

function buildMissions(program, profile) {
  if (profile.facts.length !== program.blocks.length) {
    throw new Error(`${program.id}: facts=${profile.facts.length}, blocks=${program.blocks.length}`)
  }
  const counts = allocate(program.missionCount, program.blocks.length)
  const missions = []
  let serial = 1
  program.blocks.forEach((topic, topicIndex) => {
    const fact = profile.facts[topicIndex]
    for (let step = 0; step < counts[topicIndex]; step += 1) {
      const [angle, objective, prompt, practice, evidence] = angles[step]
      const isBoss = serial === program.missionCount
      const answer = `${practice} Рабочее правило темы: ${fact}`
      const wrongA = distractors[(topicIndex + step) % distractors.length]
      const wrongB = distractors[(topicIndex + step + 2) % distractors.length]
      const progress = serial / program.missionCount
      missions.push({
        id: `${profile.prefix}-${String(serial).padStart(3, '0')}`,
        title: isBoss ? `Итоговое испытание: ${program.title}` : `${topic}: ${angle}`,
        type: isBoss ? 'boss' : types[(serial - 1) % types.length],
        minutes: isBoss ? 25 : 7 + ((serial - 1) % 4) * 2,
        xp: isBoss ? 320 : 60 + ((serial - 1) % 6) * 10,
        difficulty: progress < 0.34 ? 'начальный' : progress < 0.75 ? 'средний' : 'продвинутый',
        objectives: [`${objective}: ${topic.toLowerCase()}`],
        intro: `${profile.case} В теме «${topic}» рабочее правило формулируется так: ${fact} Практика этой миссии — ${practice.toLowerCase()}`,
        productionContext: `На этапе «${angle}» результатом работы считается не только преобразованный набор, но и доказательство: ${evidence.toLowerCase()}.`,
        task: {
          prompt: `${prompt} Контекст: ${topic}.`,
          options: [answer, wrongA, wrongB],
          answer,
          explanation: `${fact} Поэтому правильный следующий шаг — ${practice.toLowerCase()} Так решение сохраняет семантику данных и остаётся независимо проверяемым.`
        },
        hints: [`Сначала назови единицу наблюдения и ожидаемый инвариант для темы «${topic}».`]
      })
      serial += 1
    }
  })
  return missions
}

const requestedIds = new Set(process.argv.slice(2))
const programs = JSON.parse(await readFile(programsPath, 'utf8'))
for (const program of programs) {
  if (requestedIds.size && !requestedIds.has(program.id)) continue
  const profile = profiles[program.id]
  if (!profile) continue
  const course = {
    id: program.id,
    title: program.title,
    description: profile.description,
    category: profile.category,
    level: profile.level,
    skills: program.blocks,
    missions: buildMissions(program, profile)
  }
  const courseDir = resolve(dataRoot, program.id)
  await mkdir(courseDir, { recursive: true })
  await writeFile(resolve(courseDir, 'course.json'), `${JSON.stringify(course, null, 2)}\n`, 'utf8')
  program.status = 'ready'
}

await writeFile(programsPath, `${JSON.stringify(programs, null, 2)}\n`, 'utf8')
